    public function run(): void
    {
        foreach ($this->pages() as $page) {
            // A paragraph that is already a block tag (e.g. a <ul> list) is used as-is;
            // plain text is wrapped in <p>.
            $body = collect($page['paragraphs'])
                ->map(fn ($p) => str_starts_with($p, '<') ? $p : "<p>{$p}</p>")
                ->implode('');

            Page::updateOrCreate(['slug' => $page['slug']], [
                'title' => $page['title'],
                'body' => PostBody::sanitize($body),
                'meta_description' => $page['meta_description'],
                'is_published' => true,
                'published_at' => now()->subDays($page['daysAgo'] ?? 30),
            ]);
        }
    }

